<h2>Objet</h2>
<p>
    Les présentes conditions générales d'utilisation encadrent l'accès et l'usage du panel
    d'administration Safe Campus, réservé aux membres autorisés de l'équipe éditoriale
    (webmasters et rédacteurs).
</p>

<h2>Comptes utilisateurs</h2>
<p>
    Contrairement au site public, les comptes de ce panel sont nominatifs. La création d'un
    compte nécessite le nom, le prénom, l'adresse email et le numéro de téléphone de la personne
    habilitée. Ces informations sont utilisées exclusivement pour la gestion des accès et
    l'identification des actions effectuées dans le panel.
</p>

<h2 id="donnees-personnelles">Données personnelles</h2>
<p>
    <strong>Données collectées</strong> : nom, prénom, adresse email, numéro de téléphone, mot de
    passe (conservé haché, jamais en clair) et rôle attribué. Elles servent uniquement à gérer
    les accès et à identifier les actions effectuées dans le panel.
</p>
<p><strong>Durées de conservation</strong> :</p>
<ul>
    <li>Demande d'inscription : jusqu'à sa validation ou son refus par un administrateur.</li>
    <li>
        Compte actif : pendant la durée de la fonction. Un compte sans connexion depuis 3 ans est
        supprimé automatiquement.
    </li>
    <li>
        Journal d'audit (identifiant du compte, action, adresse IP, date) : 365 jours, y compris après la
        suppression du compte, au titre de la sécurité.
    </li>
    <li>Session de connexion : cookie de session, expirée après 120 minutes d'inactivité.</li>
</ul>
<p>
    <strong>Vos droits</strong> : accès, rectification, effacement, opposition et limitation. Pour
    faire supprimer votre compte, adressez votre demande à un administrateur ou au délégué à la
    protection des données de l'UNC (<a href="mailto:dpo@unc.nc">dpo@unc.nc</a>). Elle est traitée
    dans un délai d'un mois. Les bases légales et le régime juridique applicable en
    Nouvelle-Calédonie sont en cours de validation par le DPO.
</p>

<h2>Responsabilités</h2>
<p>
    Chaque titulaire de compte est responsable des actions effectuées avec ses identifiants et
    s'engage à ne pas les partager. Toute anomalie ou suspicion d'accès non autorisé doit être
    signalée sans délai.
</p>

